<?php

declare(strict_types=1);

namespace Spora\Http;

use Spora\Auth\AuthService;
use Spora\Models\MediaAsset;
use Spora\Services\AssetStreamer;
use Spora\Services\LocalAssetStore;
use Spora\Services\MediaArchive\MediaArchiveService;
use Spora\Services\MediaArchive\MediaAssetAccess;
use Spora\Services\MediaArchive\MediaScriptableTypes;
use Spora\Services\PrincipalResolver;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Symfony\Component\HttpFoundation\JsonResponse;
use Symfony\Component\HttpFoundation\Response;

/**
 * Serves files referenced by the {@see MediaArchiveService}.
 *
 * Route: `GET /api/v1/assets/{filename}` — registered with
 * {@see Middleware\AuthMiddleware} (see
 * {@see \Spora\Core\RouteDefinitions}). URL form is
 * `/api/v1/assets/<uuid>`, where the UUID is the row's primary key.
 *
 * Authorization mirrors the listing query's ownership union so the
 * asset bytes are reachable for every row the listing endpoint
 * surfaces — direct upload (`media_assets.user_id`) or generated by
 * an agent the caller can act as. Agent-side check goes through
 * `PrincipalResolver::isVisibleTo($agentId, $userId)`: any principal
 * a user can act as (own user-principal OR group-principals of their
 * groups) confers visibility on the agent's media. This matches the
 * scoping the `MediaArchiveService::list()` query uses after the
 * principal-model migration. Admins bypass. Non-visible callers get a
 * 404 to avoid leaking UUID existence.
 *
 * Migration 0067 cut `agents.user_id` — the previous controller
 * version read `PrincipalResolver::ownerUserId()` (first-group-owner
 * fallback), which wrongly returned 404 for plain group members.
 * `isVisibleTo` is the correct axis for this controller because the
 * listing endpoint surfaces group-owned media to every group member,
 * and the bytes URL must reach them too.
 *
 * Pre-refactor rows whose URL was returned to the LLM in the legacy
 * `<token>.<ext>` HMAC form skip the ownership check — they were minted
 * under the "URL is the token" model and predate this control.
 */
final class AssetController
{
    public function __construct(
        private readonly MediaArchiveService $archive,
        private readonly LocalAssetStore $local,
        private readonly AssetStreamer $streamer,
        private readonly AuthService $auth,
        private readonly ?PrincipalResolver $resolver = null,
    ) {}

    public function show(string $filename): Response
    {
        // Accept both `/api/v1/assets/<uuid>` and `/api/v1/assets/<uuid>.<ext>`.
        // UUIDs never contain dots, so a trailing `.<ext>` is safe to strip
        // here without affecting the legacy HMAC-token fallback path.
        $uuid = $this->stripExtension($filename);

        $asset = $this->archive->find($uuid);
        if ($asset !== null) {
            return $this->streamOwnedAsset($asset);
        }

        $resolved = $this->local->resolve($filename);
        if ($resolved !== null) {
            $response = new BinaryFileResponse($resolved['path'], 200, ['Content-Type' => $resolved['mime']]);
            $response->headers->set('Cache-Control', AssetStreamer::CACHE_HEADER);
            // The legacy path bypasses {@see AssetStreamer}, so the serving
            // headers are applied here too — a rule that holds on one path
            // and not another is not a rule.
            $response->headers->add(MediaScriptableTypes::headersFor($resolved['mime']));

            return $response;
        }

        return $this->notFound();
    }

    /**
     * Return the UUID portion of a public asset filename, stripping any
     * `.ext` suffix the browser appended for filename hints. UUIDs match
     * `xxxxxxxx-xxxx-xxxx-xxxx-xxxxxxxxxxxx` (36 chars); anything after
     * the 36th char is treated as the extension. Inputs without a `.`
     * are returned unchanged.
     */
    private function stripExtension(string $filename): string
    {
        if (preg_match('/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(.+)$/i', $filename) === 1) {
            return substr($filename, 0, 36);
        }
        return $filename;
    }

    /**
     * Non-owners get the standard 404 envelope so we don't leak which
     * UUIDs exist in the archive.
     */
    private function streamOwnedAsset(MediaAsset $asset): Response
    {
        if (!$this->access()->canRead($asset)) {
            return $this->notFound();
        }
        return $this->streamAsset($asset);
    }

    /**
     * The ownership union, shared with the embed route.
     *
     * {@see MediaAssetAccess} owns the definition — admins bypass, and
     * everyone else must own the row directly or own an agent that
     * produced it — so "may read this" has one answer rather than two that
     * can drift.
     */
    private function access(): MediaAssetAccess
    {
        return new MediaAssetAccess($this->auth, $this->resolver);
    }

    private function streamAsset(MediaAsset $asset): Response
    {
        return $this->streamer->stream($asset) ?? $this->notFound();
    }

    private function notFound(): JsonResponse
    {
        return new JsonResponse(
            ['error' => ['code' => 'asset_not_found', 'message' => 'Asset not found.']],
            404,
        );
    }
}
